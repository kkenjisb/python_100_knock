# 問題 25 条件分岐（elif、else）
#
# 変数 x に数値 10 を代入してください。
# elif と else を使って変数 x の大きさを判定し、結果に応じて次のようにメッセージを出力してください。
#
# (1) 10 より大きい場合: "xは10より大きい"
# (2) 上記以外で 5 より大きい場合: "xは5より大きいが、10以下"
# (3) 上記以外の場合: "xは5以下"


def main() -> None:
    x = 10
    if x > 10:
        print("xは10より大きい")
    elif x > 5:
        print("xは5より大きいが、10以下")
    else:
        print("xは5以下")
        

if __name__ == "__main__":
    main()
